alter table public.timeline_saved_posts enable row level security;
alter table public.timeline_shares enable row level security;

drop policy if exists timeline_comments_read on public.timeline_comments;
create policy timeline_comments_read
on public.timeline_comments
for select
to authenticated
using (
  auth.uid() is not null
  and exists (
    select 1
    from public.timeline_posts p
    where p.id = timeline_comments.post_id
      and not exists (
        select 1
        from public.user_blocks b
        where
          (b.blocker_id = auth.uid() and b.blocked_id = p.user_id)
          or
          (b.blocker_id = p.user_id and b.blocked_id = auth.uid())
      )
  )
  and not exists (
    select 1
    from public.user_blocks b
    where
      (b.blocker_id = auth.uid() and b.blocked_id = timeline_comments.user_id)
      or
      (b.blocker_id = timeline_comments.user_id and b.blocked_id = auth.uid())
  )
);

