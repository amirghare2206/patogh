-- Patogh V14 - Timeline Social Features (staging-ready hardened migration)
-- Scope: comments, saved posts, shares and V14 feed RPCs.
-- Safety: does NOT modify or replace V12 timeline RPCs.
-- Target for first execution: Staging only (project ref sxglkafhprigkeqdtanr).

-- ---------------------------------------------------------------------------
-- TABLES
-- ---------------------------------------------------------------------------

create table if not exists public.timeline_comments (
  id uuid primary key default gen_random_uuid(),
  post_id uuid not null references public.timeline_posts(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  author_name text not null default 'کاربر پاتوق',
  text text not null check (char_length(text) between 1 and 2000),
  created_at timestamptz not null default now()
);

create index if not exists timeline_comments_post_created_idx
  on public.timeline_comments(post_id, created_at, id);

create table if not exists public.timeline_saved_posts (
  post_id uuid not null references public.timeline_posts(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key(post_id, user_id)
);

create index if not exists timeline_saved_posts_user_idx
  on public.timeline_saved_posts(user_id, created_at desc);

create table if not exists public.timeline_shares (
  id bigint generated by default as identity primary key,
  post_id uuid not null references public.timeline_posts(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create index if not exists timeline_shares_post_idx
  on public.timeline_shares(post_id);

create index if not exists timeline_shares_user_idx
  on public.timeline_shares(user_id, created_at desc);

-- If a partial/manual V14 install created duplicate share rows, normalize them
-- before enforcing one logical share per user/post.
delete from public.timeline_shares newer
using public.timeline_shares older
where newer.post_id = older.post_id
  and newer.user_id = older.user_id
  and newer.id > older.id;

create unique index if not exists timeline_shares_post_user_uidx
  on public.timeline_shares(post_id, user_id);

