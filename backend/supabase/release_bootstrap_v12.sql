returns setof jsonb
language sql
stable
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'id', p.id,
    'user_id', p.user_id,
    'author_name', p.author_name,
    'role_label', p.role_label,
    'event_title', p.event_title,
    'text', p.text,
    'created_at', p.created_at,
