-- Patogh production schema for Supabase/Postgres

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  phone text,
  name text not null default 'کاربر پاتوق',
  age int,
  city text not null default 'مشهد',
  interests text[] not null default '{}',
  show_age boolean not null default true,
  allow_chat boolean not null default true,
  role text not null default 'user'
    check (role in ('user','host','admin')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.patogh_events (
  id text primary key,
  host_id uuid references auth.users(id) on delete set null,
  category_id text not null,
  title text not null,
  subtitle text not null default '',
  date_label text not null default '',
  time_label text not null default '',
  area text not null default 'مشهد',
  exact_location_note text not null default '',
  price bigint not null default 0,
  capacity int not null default 6,
  reserved_count int not null default 0,
  women_only boolean not null default false,
  discounted boolean not null default false,
  discount_percent int not null default 0,
  description text not null default '',
  participants text[] not null default '{}',
  tags text[] not null default '{}',
  published boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.reservations (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  event_id text not null references public.patogh_events(id) on delete cascade,
  status text not null default 'reserved'
    check (status in ('reserved','confirmed','waitlist','cancelled')),
  payment_status text not null default 'unpaid'
    check (payment_status in ('unpaid','pending','paid','failed','refunded')),
  amount bigint not null default 0,
  created_at timestamptz not null default now(),
  unique(user_id, event_id)
);

create table if not exists public.favorites (
  user_id uuid not null references auth.users(id) on delete cascade,
  event_id text not null references public.patogh_events(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key(user_id, event_id)
);

create table if not exists public.chat_messages (
  id bigint generated by default as identity primary key,
  room_id text not null,
  user_id uuid not null references auth.users(id) on delete cascade,
  text text not null check (char_length(text) between 1 and 4000),
  created_at timestamptz not null default now()
);

create table if not exists public.device_tokens (
  token text primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  platform text not null default 'web',
  updated_at timestamptz not null default now()
);

create table if not exists public.notifications (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  body text not null,
  data jsonb not null default '{}'::jsonb,
  read_at timestamptz,
  created_at timestamptz not null default now()
);

