alter table public.favorites enable row level security;
alter table public.chat_messages enable row level security;
alter table public.device_tokens enable row level security;
alter table public.notifications enable row level security;

drop policy if exists "profiles_self_select" on public.profiles;
create policy "profiles_self_select"
on public.profiles for select
using (auth.uid() = id);

drop policy if exists "profiles_self_write" on public.profiles;
create policy "profiles_self_write"
on public.profiles for all
using (auth.uid() = id)
with check (auth.uid() = id);

drop policy if exists "events_public_read" on public.patogh_events;
create policy "events_public_read"
on public.patogh_events for select
using (published = true);

drop policy if exists "events_host_insert" on public.patogh_events;
create policy "events_host_insert"
on public.patogh_events for insert
with check (
  auth.uid() = host_id
  and exists (
    select 1 from public.profiles p
    where p.id = auth.uid()
      and p.role in ('host','admin')
  )
);

drop policy if exists "events_host_update" on public.patogh_events;
create policy "events_host_update"
on public.patogh_events for update
using (
  auth.uid() = host_id
  or exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.role = 'admin'
  )
);

drop policy if exists "reservations_self" on public.reservations;
create policy "reservations_self"
on public.reservations for all
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

drop policy if exists "favorites_self" on public.favorites;
create policy "favorites_self"
on public.favorites for all
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

drop policy if exists "chat_authenticated_read" on public.chat_messages;
create policy "chat_authenticated_read"
on public.chat_messages for select
using (auth.role() = 'authenticated');

drop policy if exists "chat_self_insert" on public.chat_messages;
create policy "chat_self_insert"
on public.chat_messages for insert
with check (auth.uid() = user_id);

drop policy if exists "tokens_self" on public.device_tokens;
create policy "tokens_self"
on public.device_tokens for all
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

drop policy if exists "notifications_self" on public.notifications;
create policy "notifications_self"
on public.notifications for select
using (auth.uid() = user_id);

create or replace function public.reserve_event(
  p_event_id text,
  p_waitlist_only boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user uuid := auth.uid();
  v_capacity int;
  v_reserved int;
  v_status text;
begin
  if v_user is null then
    raise exception 'AUTH_REQUIRED';
  end if;

  select capacity
  into v_capacity
  from public.patogh_events
  where id = p_event_id
  for update;

  if v_capacity is null then
    raise exception 'EVENT_NOT_FOUND';
  end if;

  select count(*)
  into v_reserved
  from public.reservations
  where event_id = p_event_id
    and status in ('reserved','confirmed');

  if p_waitlist_only or v_reserved >= v_capacity then
    v_status := 'waitlist';
  else
    v_status := 'reserved';
  end if;

  insert into public.reservations (
    user_id,
    event_id,
    status
  )
  values (
    v_user,
    p_event_id,
    v_status
  )
  on conflict (user_id, event_id)
  do update set status = excluded.status;

  update public.patogh_events
  set reserved_count = (
    select count(*)
    from public.reservations
    where event_id = p_event_id
      and status in ('reserved','confirmed')
  )
  where id = p_event_id;

  return jsonb_build_object('status', v_status);
end;
$$;

grant execute on function public.reserve_event(text, boolean)
to authenticated;
